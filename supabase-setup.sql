-- 1. Cipta jadual senarai aplikasi (apps)
CREATE TABLE IF NOT EXISTS public.apps (
  id TEXT PRIMARY KEY,
  sort_order INTEGER DEFAULT 0,
  name TEXT NOT NULL,
  is_open BOOLEAN NOT NULL DEFAULT true,
  subtitle TEXT DEFAULT '',
  developer TEXT DEFAULT '',
  category TEXT DEFAULT 'utiliti',
  category_name TEXT DEFAULT '',
  version TEXT DEFAULT 'v1.0.0',
  file_size TEXT DEFAULT '0 MB',
  rating NUMERIC DEFAULT 4.8,
  reviews TEXT DEFAULT '0',
  downloads TEXT DEFAULT '0',
  age_rating TEXT DEFAULT '3+',
  icon TEXT DEFAULT '',
  apk_file TEXT DEFAULT '',
  badge TEXT DEFAULT '',
  featured BOOLEAN DEFAULT false,
  banner_color TEXT DEFAULT 'linear-gradient(135deg, #01875f 0%, #055b41 100%)',
  description TEXT DEFAULT '',
  highlights JSONB DEFAULT '[]'::jsonb,
  features JSONB DEFAULT '[]'::jsonb,
  whats_new TEXT DEFAULT '',
  min_android TEXT DEFAULT 'Android 6.0+',
  package_name TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Cipta jadual log aktiviti pengguna & muat turun (activity_logs)
CREATE TABLE IF NOT EXISTS public.activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  app_id TEXT,
  app_name TEXT,
  app_version TEXT,
  file_size TEXT,
  user_name TEXT,
  user_email TEXT,
  provider TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.apps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

-- Polisi untuk jadual apps:
-- Semua pelawat boleh BACA senarai aplikasi
DROP POLICY IF EXISTS "Public read apps" ON public.apps;
CREATE POLICY "Public read apps"
  ON public.apps FOR SELECT
  TO anon, authenticated
  USING (true);

-- Hanya Admin yang log masuk (authenticated) boleh TAMBAH / EDIT / PADAM aplikasi
DROP POLICY IF EXISTS "Admin insert apps" ON public.apps;
CREATE POLICY "Admin insert apps"
  ON public.apps FOR INSERT
  TO authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Admin update apps" ON public.apps;
CREATE POLICY "Admin update apps"
  ON public.apps FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Admin delete apps" ON public.apps;
CREATE POLICY "Admin delete apps"
  ON public.apps FOR DELETE
  TO authenticated
  USING (true);

-- Polisi untuk jadual activity_logs:
-- Pelawat boleh REKOD aktiviti log masuk & muat turun
DROP POLICY IF EXISTS "Public insert logs" ON public.activity_logs;
CREATE POLICY "Public insert logs"
  ON public.activity_logs FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

-- Hanya Admin yang log masuk boleh LIHAT log aktiviti
DROP POLICY IF EXISTS "Admin read logs" ON public.activity_logs;
CREATE POLICY "Admin read logs"
  ON public.activity_logs FOR SELECT
  TO authenticated
  USING (true);

-- 4. Cipta Storage Bucket untuk simpan fail ikon & APK (pilihan jika mahu upload terus dari Admin Panel)
INSERT INTO storage.buckets (id, name, public)
VALUES ('store-files', 'store-files', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Public read store files" ON storage.objects;
CREATE POLICY "Public read store files"
  ON storage.objects FOR SELECT
  TO anon, authenticated
  USING (bucket_id = 'store-files');

DROP POLICY IF EXISTS "Admin upload store files" ON storage.objects;
CREATE POLICY "Admin upload store files"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (bucket_id = 'store-files');

DROP POLICY IF EXISTS "Admin update store files" ON storage.objects;
CREATE POLICY "Admin update store files"
  ON storage.objects FOR UPDATE
  TO authenticated
  USING (bucket_id = 'store-files');

DROP POLICY IF EXISTS "Admin delete store files" ON storage.objects;
CREATE POLICY "Admin delete store files"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (bucket_id = 'store-files');

