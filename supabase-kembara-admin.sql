values ('admin_pin', crypt('TUKAR_PIN_ANDA', gen_salt('bf')), now())
on conflict (key) do update
set value_hash = excluded.value_hash,
    updated_at = now();

-- 2. Jadual Pengguna Berdaftar Kembara Masjid (TIDAK boleh dibaca secara awam)
create table if not exists public.kembara_app_users (
  account_id text primary key,
  display_name text not null,
  email text not null,
  app_version text default '1.0.0',
  device_model text default '',
  android_sdk integer default 0,
  unique_places_count integer default 0,
  mosque_count integer default 0,
  surau_count integer default 0,
  states_unlocked_count integer default 0,
  open_count integer default 1,
  first_seen_at timestamptz default now(),
  last_seen_at timestamptz default now()
);

create index if not exists idx_kembara_users_last_seen
  on public.kembara_app_users (last_seen_at desc);

alter table public.kembara_app_users enable row level security;
-- Sengaja TIADA polisi SELECT awam supaya emel pengguna dilindungi!

-- 3. Jadual Foto Rasmi Masjid/Surau (Bacaan awam oleh aplikasi, suntingan hanya melalui PIN Admin)
create table if not exists public.mosque_photos (
  id bigint generated by default as identity primary key,
  place_id text,
  place_name text not null,
  latitude double precision,
  longitude double precision,
  photo_url text not null,
  uploaded_by text default 'admin',
  created_at timestamptz default now()
);

alter table public.mosque_photos enable row level security;

drop policy if exists "Public read mosque photos" on public.mosque_photos;
create policy "Public read mosque photos"
  on public.mosque_photos
  for select
  using (true);

-- 4. RPC Aplikasi: Rekod aktiviti pengguna (tulis sahaja, tiada GPS)
create or replace function public.record_kembara_user_activity(
  p_account_id text,
  p_display_name text,
  p_email text,
  p_app_version text default '1.0.0',
  p_device_model text default '',
  p_android_sdk integer default 0,
  p_unique_places_count integer default 0,
  p_mosque_count integer default 0,
  p_surau_count integer default 0,
  p_states_unlocked_count integer default 0
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $func$
begin
  if p_account_id is null or length(trim(p_account_id)) = 0 then
    return;
  end if;
  if p_email is null or length(trim(p_email)) = 0 then
    return;
  end if;

  insert into public.kembara_app_users (
    account_id,
    display_name,
    email,
    app_version,
    device_model,
    android_sdk,
    unique_places_count,
    mosque_count,
    surau_count,
    states_unlocked_count,
    open_count,
    first_seen_at,
    last_seen_at
  )
  values (
    left(trim(p_account_id), 128),
    left(coalesce(nullif(trim(p_display_name), ''), split_part(trim(p_email), '@', 1)), 120),
    left(lower(trim(p_email)), 160),
    left(coalesce(p_app_version, '1.0.0'), 32),
    left(coalesce(p_device_model, ''), 64),
    greatest(coalesce(p_android_sdk, 0), 0),
    greatest(coalesce(p_unique_places_count, 0), 0),
    greatest(coalesce(p_mosque_count, 0), 0),
    greatest(coalesce(p_surau_count, 0), 0),
    greatest(coalesce(p_states_unlocked_count, 0), 0),
    1,
    now(),
    now()
  )
  on conflict (account_id) do update set
    display_name = excluded.display_name,
    email = excluded.email,
    app_version = excluded.app_version,
    device_model = excluded.device_model,
    android_sdk = excluded.android_sdk,
    unique_places_count = greatest(public.kembara_app_users.unique_places_count, excluded.unique_places_count),
    mosque_count = greatest(public.kembara_app_users.mosque_count, excluded.mosque_count),
    surau_count = greatest(public.kembara_app_users.surau_count, excluded.surau_count),
    states_unlocked_count = greatest(public.kembara_app_users.states_unlocked_count, excluded.states_unlocked_count),
    open_count = public.kembara_app_users.open_count + 1,
    last_seen_at = now();
end;
$func$;

grant execute on function public.record_kembara_user_activity(text, text, text, text, text, integer, integer, integer, integer, integer) to anon, authenticated;

-- 5. RPC Dashboard Admin: Semak PIN di pelayan & pulangkan ringkasan + senarai pengguna
create or replace function public.get_kembara_admin_dashboard(p_admin_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $func$
declare
  v_hash text;
  v_summary jsonb;
  v_users jsonb;
  v_photos jsonb;
begin
  select value_hash into v_hash
  from public.kembara_admin_config
  where key = 'admin_pin';

  if v_hash is null or p_admin_pin is null or crypt(p_admin_pin, v_hash) <> v_hash then
    raise exception 'PIN Admin tidak sah' using errcode = '28000';
  end if;

  select jsonb_build_object(
    'total_users', count(*),
    'active_today', count(*) filter (where last_seen_at >= now() - interval '24 hours'),
    'active_7d', count(*) filter (where last_seen_at >= now() - interval '7 days'),
    'active_30d', count(*) filter (where last_seen_at >= now() - interval '30 days'),
    'total_unique_checkins', coalesce(sum(unique_places_count), 0),
    'total_opens', coalesce(sum(open_count), 0)
  )
  into v_summary
  from public.kembara_app_users;

  select coalesce(jsonb_agg(u order by u.last_seen_at desc), '[]'::jsonb)
  into v_users
  from (
    select
      display_name,
      email,
      app_version,
      device_model,
      android_sdk,
      unique_places_count,
      mosque_count,
      surau_count,
      states_unlocked_count,
      open_count,
      first_seen_at,
      last_seen_at
    from public.kembara_app_users
    order by last_seen_at desc
    limit 500
  ) u;

  select coalesce(jsonb_agg(p order by p.created_at desc), '[]'::jsonb)
  into v_photos
  from (
    select id, place_id, place_name, latitude, longitude, photo_url, created_at
    from public.mosque_photos
    order by created_at desc
    limit 200
  ) p;

  return jsonb_build_object(
    'summary', v_summary,
    'users', v_users,
    'photos', v_photos
  );
end;
$func$;

grant execute on function public.get_kembara_admin_dashboard(text) to anon, authenticated;

-- 6. RPC Admin: Tambah / Padam Foto Rasmi Masjid/Surau dari Dashboard Web
create or replace function public.admin_upsert_mosque_photo(
  p_admin_pin text,
  p_place_name text,
  p_photo_url text,
  p_latitude double precision default null,
  p_longitude double precision default null,
  p_place_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $func$
declare
  v_hash text;
  v_id bigint;
begin
  select value_hash into v_hash from public.kembara_admin_config where key = 'admin_pin';
  if v_hash is null or p_admin_pin is null or crypt(p_admin_pin, v_hash) <> v_hash then
    raise exception 'PIN Admin tidak sah' using errcode = '28000';
  end if;

  if p_place_name is null or length(trim(p_place_name)) < 3 then
    raise exception 'Nama masjid/surau tidak sah';
  end if;
  if p_photo_url is null or p_photo_url not like 'https://%' then
    raise exception 'URL foto mesti bermula dengan https://';
  end if;

  insert into public.mosque_photos (place_id, place_name, latitude, longitude, photo_url)
  values (nullif(trim(p_place_id), ''), trim(p_place_name), p_latitude, p_longitude, trim(p_photo_url))
  returning id into v_id;

  return jsonb_build_object('ok', true, 'id', v_id);
end;
$func$;

grant execute on function public.admin_upsert_mosque_photo(text, text, text, double precision, double precision, text) to anon, authenticated;

create or replace function public.admin_delete_mosque_photo(
  p_admin_pin text,
  p_photo_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $func$
declare
  v_hash text;
begin
  select value_hash into v_hash from public.kembara_admin_config where key = 'admin_pin';
  if v_hash is null or p_admin_pin is null or crypt(p_admin_pin, v_hash) <> v_hash then
    raise exception 'PIN Admin tidak sah' using errcode = '28000';
  end if;

  delete from public.mosque_photos where id = p_photo_id;
  return jsonb_build_object('ok', true);
end;
$func$;

grant execute on function public.admin_delete_mosque_photo(text, bigint) to anon, authenticated;
