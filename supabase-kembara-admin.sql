create extension if not exists pgcrypto;

-- 1. Jadual Konfigurasi Rahsia Admin (TIDAK boleh dibaca oleh orang awam)
create table if not exists public.kembara_admin_config (
  key text primary key,
  value_hash text not null,
  updated_at timestamptz default now()
);

alter table public.kembara_admin_config enable row level security;
-- Sengaja TIADA polisi SELECT/INSERT awam pada kembara_admin_config!

-- TUKAR 'TUKAR_PIN_ANDA' KEPADA PIN / KATA LALUAN ADMIN ANDA SENDIRI SEBELUM RUN:
