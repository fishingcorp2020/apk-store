-- Kembara Masjid: Jadual Foto Rasmi Masjid/Surau (Supabase)
-- Jalankan SQL ini sekali sahaja di Supabase SQL Editor (projek jdbrqyhuckmuvjxtqnxe)
-- Selepas itu pentadbir boleh tambah URL foto masjid/surau dan ia terus muncul dalam aplikasi!

create table if not exists public.mosque_photos (
  id bigint generated by default as identity primary key,
  place_id text,
  place_name text not null,
  latitude double precision,
  longitude double precision,
  photo_url text not null,
  uploaded_by text default 'admin',
  created_at timestamptz default now()
);

alter table public.mosque_photos enable row level security;

drop policy if exists "Public read mosque photos" on public.mosque_photos;
create policy "Public read mosque photos"
  on public.mosque_photos
  for select
  using (true);

